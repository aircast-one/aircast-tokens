package tokens

import (
	"fmt"
	"strings"
)

type Role struct {
	Name  string
	Color RGB
}

type Native struct {
	Scheme []Role
	Status []Role
}

const (
	containerWeight = 0.3
	statusWeight    = 0.25
)

var black = RGB{}

func Material(mode Mode) (Native, error) {
	t, err := Palette(mode)
	if err != nil {
		return Native{}, err
	}
	required := []string{"background", "foreground", "card", "sidebar", "primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground", "faint", "accent", "destructive", "destructive-foreground", "success", "warning", "border", "input"}
	for _, name := range required {
		if _, ok := t[name]; !ok {
			return Native{}, fmt.Errorf("tokens.css %s mode has no --%s", mode, name)
		}
	}
	rgb := func(name string) RGB { return t[name].SRGB() }
	bg := rgb("background")
	fg := rgb("foreground")
	on := func(c RGB) RGB {
		if Contrast(c, fg) >= Contrast(c, bg) {
			return fg
		}
		return bg
	}
	tint := func(name string, weight float64) RGB { return Mix(t[name], t["background"], weight).SRGB() }
	surfaces := map[Mode][5]RGB{
		Dark:  {bg, rgb("sidebar"), rgb("card"), Mix(t["secondary"], t["card"], 0.5).SRGB(), rgb("secondary")},
		Light: {rgb("card"), rgb("sidebar"), rgb("secondary"), Over(OKLCH{L: t["border"].L, C: t["border"].C, H: t["border"].H, Alpha: 0.5}, rgb("secondary")), rgb("border")},
	}[mode]
	bright := map[Mode]RGB{Dark: rgb("accent"), Light: bg}[mode]
	warning := rgb("warning")
	return Native{
		Scheme: []Role{
			{"primary", rgb("primary")},
			{"onPrimary", rgb("primary-foreground")},
			{"primaryContainer", tint("primary", containerWeight)},
			{"onPrimaryContainer", fg},
			{"secondary", rgb("faint")},
			{"onSecondary", on(rgb("faint"))},
			{"secondaryContainer", rgb("secondary")},
			{"onSecondaryContainer", rgb("secondary-foreground")},
			{"tertiary", warning},
			{"onTertiary", on(warning)},
			{"tertiaryContainer", tint("warning", statusWeight)},
			{"error", rgb("destructive")},
			{"onError", rgb("destructive-foreground")},
			{"errorContainer", tint("destructive", statusWeight)},
			{"onErrorContainer", fg},
			{"background", bg},
			{"onBackground", fg},
			{"surface", bg},
			{"onSurface", fg},
			{"surfaceVariant", rgb("muted")},
			{"onSurfaceVariant", rgb("muted-foreground")},
			{"outline", Over(t["input"], bg)},
			{"outlineVariant", Over(t["border"], bg)},
			{"surfaceDim", bg},
			{"surfaceBright", bright},
			{"surfaceContainerLowest", surfaces[0]},
			{"surfaceContainerLow", surfaces[1]},
			{"surfaceContainer", surfaces[2]},
			{"surfaceContainerHigh", surfaces[3]},
			{"surfaceContainerHighest", surfaces[4]},
			{"inverseSurface", fg},
			{"inverseOnSurface", bg},
			{"scrim", black},
		},
		Status: []Role{
			{"success", rgb("success")},
			{"onSuccess", on(rgb("success"))},
			{"successContainer", tint("success", statusWeight)},
			{"warning", warning},
			{"onWarning", on(warning)},
			{"warningContainer", tint("warning", statusWeight)},
		},
	}, nil
}

const generatedHeader = "// Code generated by aircast-tokens. DO NOT EDIT.\n\n"

func Kotlin(pkg string) (string, error) {
	dark, err := Material(Dark)
	if err != nil {
		return "", err
	}
	light, err := Material(Light)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.ui.graphics.Color\n\n")
	scheme := func(name, factory string, n Native) {
		fmt.Fprintf(&b, "internal val %s = %s(\n", name, factory)
		for _, r := range n.Scheme {
			fmt.Fprintf(&b, "    %s = Color(0xFF%06X),\n", r.Name, r.Color.Hex())
		}
		b.WriteString(")\n\n")
	}
	scheme("AircastDark", "darkColorScheme", dark)
	scheme("AircastLight", "lightColorScheme", light)
	b.WriteString("internal object AircastTokens {\n")
	status := func(name string, n Native) {
		fmt.Fprintf(&b, "    object %s {\n", name)
		for _, r := range n.Status {
			fmt.Fprintf(&b, "        val %s = Color(0xFF%06X)\n", r.Name, r.Color.Hex())
		}
		b.WriteString("    }\n")
	}
	status("Dark", dark)
	status("Light", light)
	b.WriteString("}\n")
	return b.String(), nil
}

func kebab(name string) string {
	var b strings.Builder
	for _, r := range name {
		if r >= 'A' && r <= 'Z' {
			b.WriteByte('-')
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}

func MaterialCSS() (string, error) {
	dark, err := Material(Dark)
	if err != nil {
		return "", err
	}
	light, err := Material(Light)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("/* Code generated by aircast-tokens. DO NOT EDIT. */\n\n")
	block := func(selector, indent string, n Native) {
		fmt.Fprintf(&b, "%s%s {\n", indent, selector)
		for _, r := range append(append([]Role{}, n.Scheme...), n.Status...) {
			fmt.Fprintf(&b, "%s\t--md-%s: #%06X;\n", indent, kebab(r.Name), r.Color.Hex())
		}
		fmt.Fprintf(&b, "%s}\n", indent)
	}
	block(":root", "", light)
	b.WriteString("\n@media (prefers-color-scheme: dark) {\n")
	block(":root:not(.light)", "\t", dark)
	b.WriteString("}\n\n")
	block(":root.dark", "", dark)
	return b.String(), nil
}

func Swift() (string, error) {
	dark, err := Material(Dark)
	if err != nil {
		return "", err
	}
	light, err := Material(Light)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("import SwiftUI\n\nextension MaterialColors {\n")
	scheme := func(name string, n Native) {
		args := make([]string, len(n.Scheme))
		for i, r := range n.Scheme {
			args[i] = fmt.Sprintf("        %s: Color(hex: 0x%06X)", r.Name, r.Color.Hex())
		}
		fmt.Fprintf(&b, "    static let %s = MaterialColors(\n%s\n    )\n", name, strings.Join(args, ",\n"))
	}
	scheme("aircastDark", dark)
	scheme("aircastLight", light)
	b.WriteString("}\n\nenum AircastTokens {\n")
	status := func(name string, n Native) {
		fmt.Fprintf(&b, "    enum %s {\n", name)
		for _, r := range n.Status {
			fmt.Fprintf(&b, "        static let %s = Color(hex: 0x%06X)\n", r.Name, r.Color.Hex())
		}
		b.WriteString("    }\n")
	}
	status("Dark", dark)
	status("Light", light)
	b.WriteString("}\n")
	return b.String(), nil
}
